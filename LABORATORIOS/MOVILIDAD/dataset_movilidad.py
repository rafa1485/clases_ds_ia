"""**Datos meteorológicos**

Se puede acceder a los datos meteorologicos con información horaria e intra horaria de la zona correspondiente NY.
Para eso seleccionamos inicialemente el año de interés y descargamos el conjunto completo de datos.
Luego se debe filtrar hasta obtener el conjunto de datos correspondientes a los días en los que se analizan los viajes.
"""

meteo_url = (
    "https://www.ncei.noaa.gov/oa/"
    "global-historical-climatology-network/hourly/"
    "access/by-year/2024/psv/"
    "GHCNh_USW00094728_2024.psv"
)

meteo_df = pd.read_csv(
    meteo_url,
    sep="|",
    low_memory=False
)

print(meteo_df.shape)
print(meteo_df.columns.tolist())

# Se debe seleccionar un subconjunto de columnas, ya que muchos datos se presume
# que no son relevantes para el problema.
columnas_clima = [
    "STATION",
    "Station_name",
    "DATE",
    "temperature",
    "dew_point_temperature",
    "relative_humidity",
    "wind_direction",
    "wind_speed",
    "wind_gust",
    "precipitation",
    "snow_depth",
    "visibility",
    "sea_level_pressure",
    "sky_condition"
]

clima = meteo_df[columnas_clima].copy()

# --------------------------------------------------
# 1. Interpretar DATE como UTC
# --------------------------------------------------

clima["DATE_UTC"] = pd.to_datetime(
    clima["DATE"],
    utc=True
)

# --------------------------------------------------
# 2. Convertir de UTC a hora local de Nueva York
# --------------------------------------------------

clima["DATE_NY"] = (
    clima["DATE_UTC"]
    .dt.tz_convert("America/New_York")
)

# --------------------------------------------------
# 3. Filtrar enero de 2024 en hora local
# --------------------------------------------------

clima_mes = clima[
    (clima["DATE_NY"] >= "2024-01-01 00:00:00-05:00") &
    (clima["DATE_NY"] <  "2024-02-01 00:00:00-05:00")
].copy()


print(clima_mes.shape)

# --------------------------------------------------
# 4. Crear una columna de hora local
# --------------------------------------------------

clima_mes["hora"] = (
    clima_mes["DATE_NY"]
    .dt.floor("h")
)

# --------------------------------------------------
# 5. Revisar cantidad de observaciones por hora
# --------------------------------------------------

observaciones_por_hora = (
    clima_mes
    .groupby("hora")
    .size()
)

print(observaciones_por_hora.value_counts())

"""# **Resumen Horario de los datos meterológicos**

Los datos meteorológicos tiene pueden tener muestras en intervalos sub horarios. Por lo que para representar el estado del tiempo meteorológico en una determinada hora hay que proceder a seleccionar una muestra representativa o agregar varias muestras para representar lo que ocurrio en esa hora en particular.
"""

# --------------------------------------------------
# 6. Variables meteorológicas numéricas
# --------------------------------------------------
# Las variables meteorológicas numericas deben ser agregadas en los casos
# que exista más de una medicion dentro de una misma hora.

variables_numericas = [
    "temperature",
    "dew_point_temperature",
    "relative_humidity",
    "wind_speed",
    "wind_gust",
    "precipitation",
    "snow_depth",
    "visibility",
    "sea_level_pressure"
]

# --------------------------------------------------
# 7. Agregar a una observación por hora
# --------------------------------------------------

clima_horario = (
    clima_mes
    .groupby("hora")[variables_numericas]
    .mean()
    .reset_index()
)

